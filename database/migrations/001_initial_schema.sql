IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'Companies')
BEGIN
  CREATE TABLE Companies (
    Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_Companies PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    CompanyName NVARCHAR(200) NOT NULL,
    TaxNumber NVARCHAR(50) NULL,
    TaxOffice NVARCHAR(150) NULL,
    Email NVARCHAR(255) NULL,
    Phone NVARCHAR(50) NULL,
    City NVARCHAR(100) NULL,
    District NVARCHAR(100) NULL,
    Address NVARCHAR(500) NULL,
    Status NVARCHAR(30) NOT NULL CONSTRAINT DF_Companies_Status DEFAULT 'PENDING',
    IsActive BIT NOT NULL CONSTRAINT DF_Companies_IsActive DEFAULT 1,
    CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Companies_CreatedAt DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL CONSTRAINT DF_Companies_UpdatedAt DEFAULT SYSUTCDATETIME(),
    CONSTRAINT CK_Companies_Status CHECK (Status IN ('PENDING', 'APPROVED', 'REJECTED', 'SUSPENDED'))
  );
END
GO

IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'Users')
BEGIN
  CREATE TABLE Users (
    Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_Users PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    CompanyId UNIQUEIDENTIFIER NULL,
    FirstName NVARCHAR(100) NOT NULL,
    LastName NVARCHAR(100) NOT NULL,
    Email NVARCHAR(255) NOT NULL,
    PasswordHash NVARCHAR(255) NOT NULL,
    Phone NVARCHAR(50) NULL,
    Role NVARCHAR(30) NOT NULL,
    IsActive BIT NOT NULL CONSTRAINT DF_Users_IsActive DEFAULT 1,
    CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Users_CreatedAt DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL CONSTRAINT DF_Users_UpdatedAt DEFAULT SYSUTCDATETIME(),
    CONSTRAINT UQ_Users_Email UNIQUE (Email),
    CONSTRAINT CK_Users_Role CHECK (Role IN ('ADMIN', 'COMPANY_USER')),
    CONSTRAINT FK_Users_Companies FOREIGN KEY (CompanyId) REFERENCES Companies(Id)
  );
END
GO

IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'Categories')
