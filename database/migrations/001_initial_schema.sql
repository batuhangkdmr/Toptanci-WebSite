GO

IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'Products')
BEGIN
  CREATE TABLE Products (
    Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_Products PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    CategoryId UNIQUEIDENTIFIER NULL,
    Name NVARCHAR(250) NOT NULL,
    Slug NVARCHAR(280) NOT NULL,
    SKU NVARCHAR(100) NULL,
    Barcode NVARCHAR(100) NULL,
    Description NVARCHAR(MAX) NULL,
    Unit NVARCHAR(50) NULL,
    Price DECIMAL(18, 2) NULL,
    StockQuantity DECIMAL(18, 3) NULL,
    IsActive BIT NOT NULL CONSTRAINT DF_Products_IsActive DEFAULT 1,
    CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Products_CreatedAt DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL CONSTRAINT DF_Products_UpdatedAt DEFAULT SYSUTCDATETIME(),
    CONSTRAINT UQ_Products_Slug UNIQUE (Slug),
    CONSTRAINT FK_Products_Categories FOREIGN KEY (CategoryId) REFERENCES Categories(Id)
  );
END
GO

IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'ProductImages')
BEGIN
  CREATE TABLE ProductImages (
    Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_ProductImages PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    ProductId UNIQUEIDENTIFIER NOT NULL,
    CloudinaryPublicId NVARCHAR(500) NOT NULL,
    SecureUrl NVARCHAR(1000) NOT NULL,
    Width INT NULL,
    Height INT NULL,
    Format NVARCHAR(20) NULL,
    SortOrder INT NOT NULL CONSTRAINT DF_ProductImages_SortOrder DEFAULT 0,
    IsPrimary BIT NOT NULL CONSTRAINT DF_ProductImages_IsPrimary DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_ProductImages_CreatedAt DEFAULT SYSUTCDATETIME(),
    CONSTRAINT FK_ProductImages_Products FOREIGN KEY (ProductId) REFERENCES Products(Id) ON DELETE CASCADE
